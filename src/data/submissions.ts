/** Count of submissions per pipeline state — drives the dashboard pipeline bar. */
export function submissionStateCounts(items: Submission[] = SUBMISSIONS): Record<SubmissionState, number> {
  const counts: Record<SubmissionState, number> = {
    Pending: 0,
    Triaged: 0,
    Accepted: 0,
    Duplicated: 0,
    Paid: 0,
  }

  for (const item of items) {
    counts[item.state] += 1
  }

  return counts
}
